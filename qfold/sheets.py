TOTAL = 4


def _material_text(case: Case) -> str:
    m = case.params.material
    return f"{m.name}, t={m.T:g}"


def _common_notes(case: Case) -> list[str]:
    m = case.params.material
    return [
        f"Inside bend radius R{m.R:g}, K-factor {m.K:g}: PLACEHOLDERS, use your fab's values.",
        "Break sharp edges. Deburr all cut edges.",
        "Hole sizes for parts are typical values; confirm with datasheets.",
        "Generated by qfold from exact model geometry. Do not scale.",
    ]


def _hole_rows(view: View, items, coord):
    """items: list of (tag, face_state, hole). coord(p3) -> (a, b) table coordinates."""
    rows = []
    for t, st, h in items:
        a, b = coord(st.to3d(*h.c))
        rows.append([t, h.label, fmt_len(round(a, 2)), fmt_len(round(b, 2)), h.size_text()])
    return rows


def _tag_holes(sh: Sheet, view: View, items):
    for t, st, h in items:
        x, y = view.P3(st.to3d(*h.c))
        r = (h.d / 2 if h.kind == "circle" else max(h.w, h.h) / 2) * view.scale
        tag(sh, x, y, r, t)


def _flat(sh: Sheet, fp: FlatPattern, x0: float, y0: float, s: float, label: str,
          tags: dict[str, str]):
    """Draw a flat pattern with its lower-left at paper (x0, y0 + height)."""
    H = fp.size[1]

    def P(p):
        return (x0 + p[0] * s, y0 + (H - p[1]) * s)

    for a, b in fp.lines:
        sh.line(*P(a), *P(b))
    for c, r in fp.circles:
        sh.circle(*P(c), r * s)
    for c, r, a0, a1 in fp.arcs:
        sh.arc(*P(c), r * s, a0, a1)
    for p in fp.polys:
        sh.poly([P(q) for q in p])
    for b in fp.bends:
        pa, pb = P(b.a), P(b.b)
        sh.line(*pa, *pb, "bend")
        mid = ((pa[0] + pb[0]) / 2, (pa[1] + pb[1]) / 2)
        vertical = abs(pa[0] - pb[0]) < abs(pa[1] - pb[1])
        txt = f"{tags[b.name]} {b.direction} {b.angle:g}°"
        if vertical:
            sh.text(mid[0] - 1.2, mid[1], txt, 2.3, "middle", rot=-90, cls="bt")
        else:
            sh.text(mid[0], mid[1] - 1.2, txt, 2.3, "middle", cls="bt")
    W = fp.size[0]
    dim_h(sh, P((0, 0)), P((W, 0)), y0 + H * s + 9, W)
    dim_v(sh, P((0, 0)), P((0, H)), x0 - 9, H)
    sh.text(x0 + W * s / 2, y0 + H * s + 17, label, 3.0, "middle", "bold")


def _bend_rows(fp: FlatPattern, tags: dict[str, str]):
    rows = []
    for b in fp.bends:
        length = float(np.linalg.norm(b.b - b.a))
        vertical = abs(b.a[0] - b.b[0]) < 1e-6
        pos = f"X {fmt_len(round(b.a[0], 2))}" if vertical else f"Y {fmt_len(round(b.a[1], 2))}"
        rows.append([tags[b.name], b.name, b.direction, f"{b.angle:g}°", f"R{b.radius:g}",
                     fmt_len(round(length, 2)), fmt_len(round(b.allowance, 3)), pos])
    return rows


BEND_COLS = [("Tag", 10, "start"), ("Bend", 22, "start"), ("Dir", 10, "middle"),
             ("Angle", 13, "end"), ("In. R", 12, "end"), ("Length", 15, "end"),
             ("Allow.", 14, "end"), ("Centre line", 22, "end")]
HOLE_COLS = [("Tag", 9, "start"), ("Feature", 42, "start"), ("{a}", 15, "end"),
             ("{b}", 15, "end"), ("Size", 25, "end")]  # 106 mm wide


def _hole_cols(a: str, b: str):
    return [(h.format(a=a, b=b), w, al) for h, w, al in HOLE_COLS]


# ---------------------------------------------------------------------- sheets

def sheet_assembly(case: Case, res: dict, rep: Report, render_png: bytes) -> Sheet:
    p = case.params
    sh = Sheet()
    frame(sh, "Synth case: assembly", "ASSEMBLY", 1, TOTAL, _material_text(case),
          _common_notes(case), "NTS")
    sh.image(16, 14, 240, 172, render_png)

    shell = res["bodies"]["bottom_shell"]
    bb = shell["bbox"]
    rows = [["Outer width", fmt_len(round(bb[3] - bb[0], 2))],
            ["Outer depth", fmt_len(round(bb[4] - bb[1], 2))],
            ["Back height", fmt_len(round(bb[5] - bb[2], 2))],
            ["Front height (cheek)", fmt_len(p.Hf)],
            ["Panel slope", f"{np.degrees(case.slope):.2f}°"],
            ["Sheet thickness", fmt_len(p.material.T)]]
    y = table(sh, 264, 22, [("Overall", 44, "start"), ("mm", 22, "end")], rows, title="Envelope")

    bom = [["1", "Bottom shell", "1", "sheet metal, sheet 2-3"],
           ["2", "Top panel", "1", "sheet metal, sheet 4"],
           ["3", "Screw M3×6 pan head", "4", "cheek to panel lip"],
           ["4", "PEM CLS-M3-1 nut", "4", "clinched in panel lips"],
           ["5", "Screw M3 + rubber foot", "4", "base"]]
    y = table(sh, 264, y + 9, [("#", 7, "start"), ("Item", 40, "start"), ("Qty", 9, "end"),
                               ("Note", 48, "start")], bom, title="Parts and hardware")

    rows, cls = [], []
    for c in rep.checks:
        detail = c.detail if len(c.detail) <= 92 else c.detail[:89] + "…"
        rows.append([c.name, detail, c.status.upper()])
        cls.append(c.status)
    row_h = min(3.55, (283.0 - 193.0) / (len(rows) + 1))
    sh.text(16, 190, f"Checks: {rep.summary()}", 2.8, weight="bold")
    table(sh, 16, 193, [("Check", 62, "start"), ("Result", 134, "start"), ("", 13, "middle")],
          rows, row_h=row_h, size=min(2.05, row_h * 0.6), row_cls=cls)
    return sh


def sheet_shell_views(case: Case, res: dict) -> Sheet:
    p = case.params
    lay = case.shell
    s = 0.5
    sh = Sheet()
    frame(sh, "Bottom shell: views", "BOTTOM SHELL", 2, TOTAL, _material_text(case),
          _common_notes(case) + ["Third-angle projection. Hole positions from outer faces."],
          "1:2")
    vw = res["views"]
    top = View(vw["shell_top"], (0, 0, 1), (1, 0, 0), s)
    front = View(vw["shell_front"], (0, -1, 0), (1, 0, 0), s)
    right = View(vw["shell_right"], (1, 0, 0), (0, 1, 0), s)
    back = View(vw["shell_back"], (0, 1, 0), (-1, 0, 0), s)

    top.x, top.y = 32, 24
    front.x, front.y = 32, top.y + top.size[1] + 16
    right.x, right.y = front.x + front.size[0] + 14, front.y + front.size[1] - right.size[1]
    back.x, back.y = 32, front.y + front.size[1] + 34
    top.draw(sh, label="TOP")
    front.draw(sh, label="FRONT")
    right.draw(sh, label="RIGHT")
    back.draw(sh, label="REAR (viewed from behind)")

    W, D = p.W, p.D
    dim_h(sh, top.P3((0, D, 0)), top.P3((W, D, 0)), top.y - 5, W)
    dim_v(sh, top.P3((0, 0, 0)), top.P3((0, D, 0)), top.x - 7, D)
    h_front = lay.faces["front_lip"].to3d(lay.faces["front_lip"].face.outline[4][0], 0)[2]
    dim_v(sh, front.P3((0, 0, 0)), front.P3((0, 0, h_front)), front.x - 7, h_front)
    dim_v(sh, right.P3((W, 0, 0)), right.P3((W, 0, p.Hf)), right.x - 6, p.Hf)
    dim_v(sh, right.P3((W, D, 0)), right.P3((W, D, p.Hb)), right.x + right.size[0] + 7, p.Hb)
    dim_h(sh, right.P3((W, 0, 0)), right.P3((W, D, 0)), right.y + right.size[1] + 12, D,
          above=False)
    dim_v(sh, back.P3((W, D, 0)), back.P3((W, D, p.Hb)), back.x - 7, p.Hb)

    base_items = [(f"A{i + 1}", lay.faces["base"], h) for i, h in
                  enumerate(lay.faces["base"].face.holes)]
    back_items = [(f"R{i + 1}", lay.faces["back_wall"], h) for i, h in
                  enumerate(lay.faces["back_wall"].face.holes)]
    side_items = [(f"S{i + 1}", lay.faces["cheek_right"], h) for i, h in
                  enumerate(lay.faces["cheek_right"].face.holes)]
    _tag_holes(sh, top, base_items)
    _tag_holes(sh, back, back_items)
    _tag_holes(sh, right, side_items)

    x = 302
    y = table(sh, x, 24, _hole_cols("X", "Y"),
              _hole_rows(top, base_items, lambda q: (q[0], q[1])),
              title="Base holes (top view, from front-left outer corner)")
    y = table(sh, x, y + 9, _hole_cols("X", "Z"),
              _hole_rows(back, back_items, lambda q: (W - q[0], q[2])),
              title="Rear wall holes (from rear view lower-left)")
    table(sh, x, y + 9, _hole_cols("Y", "Z"),
          _hole_rows(right, side_items, lambda q: (q[1], q[2])),
          title="Cheek holes, both cheeks (from front, base)")
    return sh


def sheet_flat(case: Case, fp: FlatPattern, part_label: str, sheet_no: int,
               tags: dict[str, str], scale: float, extra_notes: list[str]) -> Sheet:
    sh = Sheet()
    frame(sh, f"{part_label}: flat pattern", part_label.upper(), sheet_no, TOTAL,
          _material_text(case),
          _common_notes(case) + extra_notes + [
              "Outside face shown. DN = bend away from viewer. DXF is the cutting master."],
          "1:2" if scale == 0.5 else f"1:{1 / scale:g}")
    w, h = fp.size[0] * scale, fp.size[1] * scale
    x0 = max(30.0, (300 - w) / 2 + 14)
    _flat(sh, fp, x0, 26, scale, f"FLAT PATTERN  {fmt_len(round(fp.size[0], 2))} × "
                                   f"{fmt_len(round(fp.size[1], 2))}", tags)
    table(sh, 24, 26 + h + 30, BEND_COLS, _bend_rows(fp, tags), title="Bends")
    return sh


def sheet_panel(case: Case, res: dict, fp: FlatPattern, tags: dict[str, str]) -> Sheet:
    lay = case.panel
    s = 0.5
    sh = Sheet()
    frame(sh, "Top panel", "TOP PANEL", 4, TOTAL, _material_text(case),
          _common_notes(case) + ["Third-angle projection. Press PEM nuts from inside face."],
          "1:2")
    vw = res["views"]
    top = View(vw["panel_top"], (0, 0, 1), (1, 0, 0), s)
    front = View(vw["panel_front"], (0, -1, 0), (1, 0, 0), s)
    right = View(vw["panel_right"], (1, 0, 0), (0, 1, 0), s)
    top.x, top.y = 30, 22
    front.x, front.y = 30, top.y + top.size[1] + 12
    right.x, right.y = top.x + top.size[0] + 18, top.y
    top.draw(sh, label="TOP (outside face)")
    front.draw(sh, label="FRONT EDGE")
    right.draw(sh, label="RIGHT")

    st = lay.faces["panel"]
    Wp = max(p[0] for p in st.face.outline)
    Sp = max(p[1] for p in st.face.outline)
    dim_h(sh, top.P3((0, Sp, 0)), top.P3((Wp, Sp, 0)), top.y - 4.5, Wp)
    dim_v(sh, top.P3((0, 0, 0)), top.P3((0, Sp, 0)), top.x - 7, Sp)
    lip = lay.faces["lip_right"]
    depth = -lip.to3d(lip.face.outline[2][0], 0)[2]
    dim_v(sh, front.P3((Wp, 0, 0)), front.P3((Wp, 0, -depth)), front.x + front.size[0] + 6, depth)

    items = [(f"P{i + 1}", st, h) for i, h in enumerate(st.face.holes)]
    lip_items = [(f"L{i + 1}", lip, h) for i, h in enumerate(lip.face.holes)]
    _tag_holes(sh, top, items)
    _tag_holes(sh, right, lip_items)

    _flat(sh, fp, 30, front.y + front.size[1] + 22, s,
          f"FLAT PATTERN  {fmt_len(round(fp.size[0], 2))} × {fmt_len(round(fp.size[1], 2))}", tags)
    y = table(sh, 302, 22, _hole_cols("X", "Y"),
              _hole_rows(top, items, lambda q: (q[0], q[1])),
              row_h=3.9, size=2.15, title="Panel holes (from front-left corner)")
    y = table(sh, 302, y + 8, _hole_cols("Y", "Z↓"),
              _hole_rows(right, lip_items, lambda q: (q[1], -q[2])),
              row_h=3.9, size=2.15, title="Lip holes, both lips (Z below top face)")
    table(sh, 302, y + 8, [(c[0], c[1] * 0.9, c[2]) for c in BEND_COLS[:6]],
          [r[:6] for r in _bend_rows(fp, tags)], row_h=3.9, size=2.15, title="Bends")
    return sh
