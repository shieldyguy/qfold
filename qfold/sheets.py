"""Default drawing sheets for any project: assembly, one sheet per sheet metal
part, holes as assembled, and checks. `Project.build` makes them; a design can
replace the part sheets with its own (see examples/synth_case/sheets.py).

Each builder takes the build context `b` (project.Build): the project, the
kernel results, the flat patterns and the report.
"""

from __future__ import annotations

import numpy as np

from .drawing import Sheet, View, dim_h, dim_v, fmt_len, frame, table, tag
from .flat import FlatPattern

SCALES = (2.0, 1.0, 0.5, 0.4, 0.25, 0.2, 0.125, 0.1)


def clip(s: str, n: int) -> str:
    return s if len(s) <= n else s[:n - 1] + "…"


def scale_text(s: float) -> str:
    return f"{s:g}:1" if s > 1 else f"1:{1 / s:g}"


def fit_scale(w: float, h: float, room_w: float, room_h: float) -> float:
    """Largest standard scale at which w × h fits the room."""
    return next((s for s in SCALES if w * s <= room_w and h * s <= room_h), SCALES[-1])


def material_text(rule) -> str:
    return f"{rule.material}, t={rule.T:g}"


def common_notes(b) -> list[str]:
    m = b.project.rule
    return [f"Inside bend radius R{m.R:g}, K-factor {m.K:g}.",
            "Break sharp edges. Deburr all cut edges.",
            "Generated by qfold from exact model geometry. Do not scale."] + [
        n[:1].upper() + n[1:] + ("" if n.endswith(".") else ".") for n in b.project.notes]


# ------------------------------------------------------------- flat patterns

def draw_flat(sh: Sheet, fp: FlatPattern, x0: float, y0: float, s: float, label: str,
              tags: dict[str, str]):
    """Draw a flat pattern with its top-left at paper (x0, y0)."""
    H = fp.size[1]

    def P(p):
        return (x0 + p[0] * s, y0 + (H - p[1]) * s)

    for a, b in fp.lines:
        sh.line(*P(a), *P(b))
    for c, r in fp.circles:
        sh.circle(*P(c), r * s)
    for c, r, a0, a1 in fp.arcs:
        sh.arc(*P(c), r * s, a0, a1)
    for p in fp.polys:
        sh.poly([P(q) for q in p])
    for b in fp.bends:
        pa, pb = P(b.a), P(b.b)
        sh.line(*pa, *pb, "bend")
        mid = ((pa[0] + pb[0]) / 2, (pa[1] + pb[1]) / 2)
        vertical = abs(pa[0] - pb[0]) < abs(pa[1] - pb[1])
        txt = f"{tags[b.name]} {b.direction} {b.angle:g}°"
        if vertical:
            sh.text(mid[0] - 1.2, mid[1], txt, 2.3, "middle", rot=-90, cls="bt")
        else:
            sh.text(mid[0], mid[1] - 1.2, txt, 2.3, "middle", cls="bt")
    W = fp.size[0]
    dim_h(sh, P((0, 0)), P((W, 0)), y0 + H * s + 9, W)
    dim_v(sh, P((0, 0)), P((0, H)), x0 - 9, H)
    sh.text(x0 + W * s / 2, y0 + H * s + 17, label, 3.0, "middle", "bold")
    return P


def bend_rows(fp: FlatPattern, tags: dict[str, str]):
    rows = []
    for b in fp.bends:
        length = float(np.linalg.norm(b.b - b.a))
        vertical = abs(b.a[0] - b.b[0]) < 1e-6
        pos = f"X {fmt_len(round(b.a[0], 2))}" if vertical else f"Y {fmt_len(round(b.a[1], 2))}"
        rows.append([tags[b.name], b.name, b.direction, f"{b.angle:g}°", f"R{b.radius:g}",
                     fmt_len(round(length, 2)), fmt_len(round(b.allowance, 3)), pos])
    return rows


BEND_COLS = [("Tag", 10, "start"), ("Bend", 22, "start"), ("Dir", 10, "middle"),
             ("Angle", 13, "end"), ("In. R", 12, "end"), ("Length", 15, "end"),
             ("Allow.", 14, "end"), ("Centre line", 22, "end")]
HOLE_COLS = [("Tag", 9, "start"), ("Feature", 42, "start"), ("{a}", 15, "end"),
             ("{b}", 15, "end"), ("Size", 25, "end")]  # 106 mm wide


def hole_cols(a: str, b: str):
    return [(h.format(a=a, b=b), w, al) for h, w, al in HOLE_COLS]


def flat_holes(lay, fp: FlatPattern):
    """(tag, hole, position in the flat pattern) for every hole of a part."""
    return [(h.tag or "–", h, fp.at(st.to2d(*h.c))) for st in lay.faces.values()
            for h in st.face.holes]


def _rows_that_fit(n: int, room: float, row_h: float = 4.2, floor: float = 3.0):
    """Row height (and text size) that fits n rows plus a heading into room."""
    row_h = max(floor, min(row_h, room / (n + 1)))
    return row_h, min(2.3, row_h * 0.58)


# -------------------------------------------------------------------- sheets

def sheet_assembly(b) -> Sheet:
    p = b.project
    sh = Sheet()
    frame(sh, f"{p.title}: assembly", "ASSEMBLY", None, None, material_text(p.rule),
          common_notes(b), "NTS")
    sh.image(16, 14, 240, 172, b.render_png)

    bb = b.res["measure"]["assembly"]["bbox"]
    rows = [["Overall, everything", " × ".join(fmt_len(round(bb[i + 3] - bb[i], 1))
                                               for i in range(3))]]
    for part in b.parts.values():
        pb = b.res["bodies"][part.proto]["bbox"]
        rows.append([f"{part.name}, formed", " × ".join(fmt_len(round(pb[i + 3] - pb[i], 2))
                                                         for i in range(3))])
        rows.append([f"{part.name}, flat", " × ".join(fmt_len(round(v, 2))
                                                       for v in b.flats[part.name].size)])
    rows += [[k, v] for k, v in p.facts]
    y = table(sh, 264, 22, [("Size", 46, "start"), ("mm", 60, "end")], rows, title="Sizes")

    bom = [[str(i + 1), r["component"], str(r["qty"]), r["source"]]
           for i, r in enumerate(p.parts_list())]
    rh, size = _rows_that_fit(len(bom), 80, 3.9)
    y = table(sh, 264, y + 9, [("#", 7, "start"), ("Component", 46, "start"), ("Qty", 9, "end"),
                               ("Source", 44, "start")], bom, row_h=rh, size=min(size, 2.15),
              title="Parts list")

    params = p.param_rows()
    if params:
        room = max(20.0, sh.notes_top - (y + 9) - 4)
        shown = params[:int(room / 3.0) - 1]
        rh, size = _rows_that_fit(len(shown), room, 3.9)
        table(sh, 264, y + 9, [("Parameter", 50, "start"), ("Value", 56, "end")],
              [[k, clip(v, 34)] for k, v in shown], row_h=rh, size=min(size, 2.15),
              title="Parameters" + ("" if len(shown) == len(params) else " (all in report.json)"))

    sh.text(16, 192, f"Checks: {b.rep.summary()}. All {len(b.rep.checks)} are on the last "
                     "sheet.", 2.8, weight="bold")
    issues = [c for c in b.rep.checks if c.status != "pass"]
    if not issues:
        sh.text(16, 198, "Every check passes.", 2.5)
        return sh
    fit = 18
    shown = issues[:fit] if len(issues) <= fit else issues[:fit - 1]
    rows = [[c.name, clip(c.detail, 95), c.status.upper()] for c in shown]
    if len(shown) < len(issues):
        rows.append([f"… {len(issues) - len(shown)} more on the last sheet", "", ""])
    table(sh, 16, 195, [("Check", 62, "start"), ("Result", 136, "start"), ("", 14, "middle")],
          rows, row_cls=[c.status for c in shown] + [""] * (len(rows) - len(shown)))
    return sh


def sheet_part(b, part) -> Sheet:
    """Flat pattern with every hole tagged and tabled, the bend table, and
    three views of the formed part."""
    lay, fp, tags = part.lay, b.flats[part.name], b.tags[part.name]
    sh = Sheet()
    s = fit_scale(fp.size[0], fp.size[1], 250, 138)
    frame(sh, part.name, part.name.upper(), None, None, material_text(lay.body.rule),
          common_notes(b) + ["Flat pattern: outside face shown. DN = bend away from viewer. "
                             "The DXF is the cutting master; the STEP is the formed part."],
          scale_text(s))
    P = draw_flat(sh, fp, 30, 24, s, f"FLAT PATTERN  {fmt_len(round(fp.size[0], 2))} × "
                                       f"{fmt_len(round(fp.size[1], 2))}", tags)
    holes = flat_holes(lay, fp)
    for t, h, c in holes:
        r = (h.d / 2 if h.kind == "circle" else max(h.w, h.h) / 2) * s
        tag(sh, *P(c), r, t)

    y = 24.0
    if holes:
        rh, size = _rows_that_fit(len(holes), 150)
        y = table(sh, 302, y, hole_cols("X", "Y"),
                  [[t, clip(h.label, 30), fmt_len(round(c[0], 2)), fmt_len(round(c[1], 2)),
                    h.size_text()] for t, h, c in holes], row_h=rh, size=size,
                  title="Holes (flat pattern, from lower-left)") + 9
    if fp.bends:
        rh, size = _rows_that_fit(len(fp.bends), max(20.0, sh.notes_top - y - 2), 3.9)
        table(sh, 302, y, [(c[0], c[1] * 0.9, c[2]) for c in BEND_COLS], bend_rows(fp, tags),
              row_h=rh, size=min(size, 2.1), title="Bends")

    # Formed views, third angle: top, front below it would need more room, so
    # they sit in a row under the flat pattern.
    y0 = 24 + fp.size[1] * s + 30
    names = ("top", "front", "right")
    dirs = {"top": ((0, 0, 1), (1, 0, 0)), "front": ((0, -1, 0), (1, 0, 0)),
            "right": ((1, 0, 0), (0, 1, 0))}
    raw = {n: View(b.res["views"][f"{part.name}_{n}"], *dirs[n], 1.0) for n in names}
    total_w = sum(v.size[0] for v in raw.values())
    max_h = max(v.size[1] for v in raw.values())
    room_h = 287 - 12 - y0 - 8
    if room_h > 15:
        vs = fit_scale(total_w, max_h, 195 - 2 * 16, room_h)
        x = 30.0
        for n in names:
            v = View(b.res["views"][f"{part.name}_{n}"], *dirs[n], vs)
            v.x, v.y = x, y0
            v.draw(sh, label=f"{n.upper()} ({scale_text(vs)})")
            x += v.size[0] + 16
    bb = b.res["bodies"][part.proto]["bbox"]
    sh.text(30, 24 - 6, "Formed size (outside) " + " × ".join(
        fmt_len(round(bb[i + 3] - bb[i], 2)) for i in range(3)), 2.6)
    return sh


def sheet_holes(b) -> Sheet:
    """Where every hole ends up on the assembled design, and which way it faces."""
    sh = Sheet()
    frame(sh, "Holes as assembled", b.project.title.upper(), None, None,
          material_text(b.project.rule),
          ["Hole centres on the outside surface, in assembly coordinates.",
           "Facing: the direction the hole opens to, out of the part."], "NTS")
    rows = [[h["part"], h["tag"] or "–", clip(h["label"], 34), h["size"],
             fmt_len(round(h["x"], 2)), fmt_len(round(h["y"], 2)), fmt_len(round(h["z"], 2)),
             h["face"], h["facing"]] for h in b.holes]
    cols = [("Part", 26, "start"), ("Tag", 10, "start"), ("Feature", 44, "start"),
            ("Size", 24, "end"), ("X", 15, "end"), ("Y", 15, "end"), ("Z", 15, "end"),
            ("Face", 24, "start"), ("Facing", 28, "middle")]
    per_col = int((sh.notes_top - 26) / 3.0) - 1
    if len(rows) <= per_col:
        rh, size = _rows_that_fit(len(rows), sh.notes_top - 26)
        table(sh, 16, 22, cols, rows, row_h=rh, size=size)
    else:  # two columns; the left one runs the full height
        rh = 3.4
        left = min(len(rows), int((287 - 12 - 22) / rh) - 1)
        table(sh, 16, 22, cols, rows[:left], row_h=rh, size=1.95)
        table(sh, 16 + 201 + 3, 22, cols, rows[left:], row_h=rh, size=1.95)
    return sh


def sheet_checks(b) -> Sheet:
    rep = b.rep
    sh = Sheet()
    frame(sh, "Checks", b.project.title.upper(), None, None, material_text(b.project.rule),
          ["Run on every build; also in report.json.",
           "Limits come from the project's rules (a shop's, or qfold's defaults in dfm.py)."],
          "NTS")
    sh.text(16, 18, f"Checks: {rep.summary()}", 2.8, weight="bold")
    rh, size = _rows_that_fit(len(rep.checks), sh.notes_top - 24)
    rows = [[c.name, clip(c.detail, 150), c.status.upper()] for c in rep.checks]
    table(sh, 16, 22, [("Check", 82, "start"), ("Result", 204, "start"), ("", 14, "middle")],
          rows, row_h=rh, size=size, row_cls=[c.status for c in rep.checks])
    return sh
